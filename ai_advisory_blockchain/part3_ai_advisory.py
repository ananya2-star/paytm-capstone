import math

def calculate_portfolio_metrics(tickers):

    weights = {
        ticker: 1 / 3
        for ticker in tickers}

    # Get stock data using the required tool
    stock_data = {
        ticker: get_stock_data(ticker)
        for ticker in tickers}

    # CAPM expected return

    capm_returns = {
        ticker: calculate_capm_return(
            stock_data[ticker]["beta"])
        for ticker in tickers}

    portfolio_return = sum(
        weights[ticker] * capm_returns[ticker]
        for ticker in tickers)

    # Portfolio variance

    variance = 0

    # Individual variance terms
    for ticker in tickers:

        weight = weights[ticker]
        sigma = stock_data[ticker]["std_dev"]

        variance += (
            weight ** 2
            * sigma ** 2)

    # Covariance terms
    for i in range(len(tickers)):

        for j in range(i + 1, len(tickers)):

            ticker_i = tickers[i]
            ticker_j = tickers[j]

            weight_i = weights[ticker_i]
            weight_j = weights[ticker_j]

            sigma_i = stock_data[ticker_i]["std_dev"]
            sigma_j = stock_data[ticker_j]["std_dev"]

            covariance = (
                PAIRWISE_CORRELATION
                * sigma_i
                * sigma_j)

            variance += (
                2
                * weight_i
                * weight_j
                * covariance)

    portfolio_std = math.sqrt(variance)

    return {
        "tickers": tickers,
        "weights": weights,
        "capm_returns": capm_returns,
        "portfolio_return": portfolio_return,
        "portfolio_variance": variance,
        "portfolio_std": portfolio_std}

