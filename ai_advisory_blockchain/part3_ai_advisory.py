import re

def extract_signals(text):

    text_lower = text.lower()

    risk_flags = []

    # 1. Litigation risk

    if re.search(
        r"\blitigation\b|\blawsuit\b|\blegal\b|\bcourt\b",
        text_lower):
        risk_flags.append("litigation")

    # 2. Regulatory risk

    if re.search(
        r"\bregulatory\b|\bregulator\b|\bcompliance\b",
        text_lower):
        risk_flags.append("regulatory")

    # 3. Customer concentration risk

    if re.search(
        r"top\s+three\s+customers|"
        r"customer[s]?\s+account\s+for|"
        r"customer\s+concentration",
        text_lower):
        risk_flags.append("customer_concentration")

    # Hedging detection

    hedging_detected = bool(
        re.search(
            r"\bassuming\b|"
            r"\bexpect\b|"
            r"\bexpected\b|"
            r"\bcautiously\b|"
            r"\buncertainty\b|"
            r"\bvisibility\b|"
            r"\bmay\b|"
            r"\bmight\b",
            text_lower))

    # Sentiment

    confident_words = [
        "confident",
        "confidence",
        "strong",
        "optimistic",
        "approved"]

    cautious_words = [
        "cautious",
        "cautiously",
        "uncertainty",
        "limited visibility",
        "risk"]

    confident_count = sum(
        word in text_lower
        for word in confident_words)

    cautious_count = sum(
        word in text_lower
        for word in cautious_words)

    if confident_count > cautious_count:
        sentiment = "confident"

    elif cautious_count > confident_count:
        sentiment = "cautious"

    else:
        sentiment = "neutral"

    return {
        "risk_flags": risk_flags,
        "hedging_detected": hedging_detected,
        "sentiment": sentiment}

